#import <AppKit/AppKit.h>
#include <stdlib.h>
#include <string.h>

static BOOL axonkey_clipboard_has_restricted_type(NSArray<NSPasteboardType> *types) {
    if (!types || types.count == 0) {
        return NO;
    }
    static NSArray<NSString *> *restricted = nil;
    static dispatch_once_t onceToken;
    dispatch_once(&onceToken, ^{
        restricted = @[
            @"org.nspasteboard.ConcealedType",
            @"org.nspasteboard.TransientType",
            @"org.nspasteboard.AutoGeneratedType",
            @"com.agilebits.onepassword",
        ];
    });
    for (NSPasteboardType type in restricted) {
        if ([types containsObject:type]) {
            return YES;
        }
    }
    return NO;
}

long axonkey_macos_clipboard_change_count(void) {
    @autoreleasepool {
        return (long)[NSPasteboard.generalPasteboard changeCount];
    }
}

char *axonkey_macos_clipboard_read_text_if_allowed(long *out_change_count, size_t max_bytes) {
    @autoreleasepool {
        NSPasteboard *pasteboard = NSPasteboard.generalPasteboard;
        if (out_change_count) {
            *out_change_count = (long)pasteboard.changeCount;
        }
        if (axonkey_clipboard_has_restricted_type(pasteboard.types)) {
            return NULL;
        }
        if ([pasteboard availableTypeFromArray:@[NSPasteboardTypeString]] == nil) {
            return NULL;
        }
        NSString *text = [pasteboard stringForType:NSPasteboardTypeString];
        if (!text || text.length == 0) {
            return NULL;
        }
        NSUInteger utf8_len = [text lengthOfBytesUsingEncoding:NSUTF8StringEncoding];
        if (utf8_len == 0 || utf8_len > max_bytes) {
            return NULL;
        }
        const char *utf8 = [text UTF8String];
        if (!utf8) {
            return NULL;
        }
        return strdup(utf8);
    }
}

void axonkey_macos_clipboard_free_string(char *ptr) {
    free(ptr);
}
