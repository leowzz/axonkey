import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const directory = path.join(root, 'public/device-descriptors')
const output = path.join(root, 'src/devices/generatedDescriptors.ts')

export function parseDescriptorSvg(source, artworkUrl) {
  const rootAttributes = attributes(source.match(/<svg\b[^>]*>/)?.[0] ?? '')
  const device = attributes(source.match(/<ak:device\b[^>]*>/)?.[0] ?? '')
  if (rootAttributes['data-ak-schema'] !== 'axonkey.device/1' || !device.id) {
    throw new Error(`${artworkUrl}: missing device protocol metadata`)
  }
  const box = (rootAttributes.viewBox ?? '').trim().split(/\s+/).map(Number)
  if (box.length !== 4 || box[0] !== 0 || box[1] !== 0 || !box.slice(2).every(value => value > 0)) {
    throw new Error(`${artworkUrl}: expected a positive viewBox starting at 0 0`)
  }
  const regions = new Map()
  for (const match of source.matchAll(/<path\b[^>]*\bdata-ak-region=[^>]*>/g)) {
    const region = attributes(match[0])
    const id = region['data-ak-region']
    const anchor = (region['data-ak-anchor'] ?? '').trim().split(/\s+/).map(Number)
    if (regions.has(id) || !region.d || anchor.length !== 2 || !anchor.every(Number.isFinite)) {
      throw new Error(`${artworkUrl}: invalid or duplicate region ${id}`)
    }
    regions.set(id, {
      path: region.d,
      anchor: { x: anchor[0], y: anchor[1] },
      ...(region.transform ? { transform: region.transform } : {}),
    })
  }
  const seen = new Set()
  const inputs = [...source.matchAll(/<ak:input\b[^>]*>/g)]
    .map((match, index) => {
      const input = attributes(match[0])
      const id = input['legacy-key'] ?? input.id
      const region = regions.get(input.id)
      if (!id || seen.has(id) || !input.label || !input.short || !input.icon || !region) {
        throw new Error(`${artworkUrl}: input ${input.id} needs a unique ID, label, short, icon and region`)
      }
      seen.add(id)
      return {
        id,
        stableId: input.id,
        label: input.label,
        short: input.short,
        icon: input.icon,
        order: Number(input.order ?? index),
        ...region,
      }
    })
    .sort((left, right) => left.order - right.order)
  if (!inputs.length || inputs.length !== regions.size) throw new Error(`${artworkUrl}: input/region mismatch`)
  return {
    id: device.id,
    ariaLabel: device['display-name'] ?? device.model,
    artworkUrl,
    viewBox: { width: box[2], height: box[3] },
    inputs,
  }
}

export function readBundledDescriptors() {
  return Object.fromEntries(
    readdirSync(directory)
      .filter(name => name.endsWith('.svg'))
      .sort()
      .map(name => [
        name.slice(0, -4),
        parseDescriptorSvg(readFileSync(path.join(directory, name), 'utf8'), `/device-descriptors/${name}`),
      ]),
  )
}

export function generateDeviceDescriptors({ check = false } = {}) {
  const source = `// Generated by scripts/generate-device-descriptors.mjs. Edit public/device-descriptors/*.svg.\n// prettier-ignore\nexport const deviceDescriptors = ${JSON.stringify(readBundledDescriptors(), null, 2)} as const\n`
  if (check) {
    if (readFileSync(output, 'utf8').replaceAll('\r\n', '\n') !== source)
      throw new Error('Device descriptor index is stale; run npm run generate:devices')
  } else if (!existsWithContent(output, source)) {
    writeFileSync(output, source)
  }
}

function attributes(tag) {
  return Object.fromEntries(
    [...tag.matchAll(/([\w:-]+)\s*=\s*(["'])(.*?)\2/gs)].map(match => [match[1], decode(match[3])]),
  )
}

function decode(value) {
  return value.replace(/&(?:amp|lt|gt|quot|apos|#\d+|#x[0-9a-f]+);/gi, entity => {
    const known = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&apos;': "'" }
    return (
      known[entity] ??
      String.fromCodePoint(
        entity[2].toLowerCase() === 'x' ? parseInt(entity.slice(3, -1), 16) : Number(entity.slice(2, -1)),
      )
    )
  })
}

function existsWithContent(file, source) {
  try {
    return readFileSync(file, 'utf8').replaceAll('\r\n', '\n') === source
  } catch {
    return false
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateDeviceDescriptors({ check: process.argv.includes('--check') })
}
